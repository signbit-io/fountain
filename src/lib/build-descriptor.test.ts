describe('buildVaultDescriptor (offline, port of the platform descriptor builder)', () => {
  it('builds a 2-of-3 descriptor byte-identical to the platform for the same key ORDER', () => {
    const result = buildVaultDescriptor({ m: 2, keys: [KEY1, KEY2, KEY3], network: 'testnet' })
    expect(result.receive).toBe(GOLDEN_RECEIVE)
    expect(result.change).toBe(GOLDEN_CHANGE)
  })

  // IMPORTANT (verified against the platform's own descriptor builder, not assumed): the
  // "sortedmulti" name refers to BIP-67 key sorting inside the SIGNING/witness-script
  // logic — sortedmulti is functionally order-independent for spending — but the
  // DESCRIPTOR TEXT itself (and therefore its checksum) is NOT reordered; it preserves
  // whatever order the keys were passed in. So coparties building "the same vault"
  // offline must agree on key entry order, or they'll produce two descriptors that are
  // functionally equivalent but textually different (different checksums). This is a
  // real UX constraint for the offline flow — the builder UI must fix a canonical order
  // (e.g. sort by fingerprint before calling this) rather than leaving it to whoever
  // happens to type keys in first.
  it('produces a DIFFERENT descriptor string for a different key order (same keys)', () => {
    const reordered = buildVaultDescriptor({ m: 2, keys: [KEY3, KEY1, KEY2], network: 'testnet' })
    expect(reordered.receive).not.toBe(GOLDEN_RECEIVE)
    // But every key is still present — just relocated in the text.
    expect(reordered.receive).toContain(KEY1.xpub)
    expect(reordered.receive).toContain(KEY2.xpub)
    expect(reordered.receive).toContain(KEY3.xpub)
  })

  it('canonicalKeyOrder makes independently-entered key sets converge on the same descriptor', () => {
    // Three "keyholders in a room" each type the keys in whatever order they have them.
    const enteredByAlice = [KEY1, KEY2, KEY3]
    const enteredByBob = [KEY3, KEY1, KEY2]
    const enteredByCarol = [KEY2, KEY3, KEY1]

    const descAlice = buildVaultDescriptor({ m: 2, keys: canonicalKeyOrder(enteredByAlice), network: 'testnet' })
    const descBob = buildVaultDescriptor({ m: 2, keys: canonicalKeyOrder(enteredByBob), network: 'testnet' })
    const descCarol = buildVaultDescriptor({ m: 2, keys: canonicalKeyOrder(enteredByCarol), network: 'testnet' })

    expect(descBob.receive).toBe(descAlice.receive)
    expect(descCarol.receive).toBe(descAlice.receive)
    expect(descBob.change).toBe(descAlice.change)
    expect(descCarol.change).toBe(descAlice.change)
  })

  it('rejects an invalid m (below 1 or above n)', () => {
    expect(() => buildVaultDescriptor({ m: 0, keys: [KEY1, KEY2], network: 'testnet' })).toThrow(BuildDescriptorError)
    expect(() => buildVaultDescriptor({ m: 3, keys: [KEY1, KEY2], network: 'testnet' })).toThrow(BuildDescriptorError)
  })

  it('rejects a mainnet xpub on testnet and vice versa', () => {
    expect(() => validateXpub(KEY1.xpub, 'mainnet')).toThrow(BuildDescriptorError)
  })

  it('rejects a private key (tprv) passed where an xpub is expected', () => {
    expect(() =>
      buildVaultDescriptor({
        m: 1,
        keys: [{ xpub: 'tprvfakeprivatekeyvalue', fingerprint: '00000000' }],
        network: 'testnet',
      }),
    ).toThrow(/PRIVATE key/)
  })

  it('defaults an empty/missing fingerprint to 00000000 rather than throwing', () => {
    const result = buildVaultDescriptor({ m: 1, keys: [{ xpub: KEY1.xpub, fingerprint: '' }], network: 'testnet' })
    expect(result.receive).toContain('[00000000/')
  })
})

/*
  🔒 THE MAJORITY RULE — the ONE case where this library BLOCKS rather than warns.

  Deliberately identical to the SignBit platform's importer rule of the same name, so a vault
  built here is a shape that platform will adopt. There is NO build-time link between the two
  repos: these tests ARE the compatibility contract, and they are what notices if either side
  moves. See build-descriptor.ts's POLICY REFUSAL block.
*/
describe('minMajorityThreshold / the majority refusal', () => {
  /*
    Extra keys, derived rather than hardcoded. The golden vector above needs BYTE-exact xpubs
    because it pins descriptor output; these tests only need valid, distinct, testnet keys at
    the right path, so deriving them keeps the fixture honest without five more 111-char
    constants. Same seed-bytes convention as KEY1/2/3 (Buffer.alloc(32, n)).
  */
  function keyAt(seedByte: number): { xpub: string; fingerprint: string } {
    const master = descriptors.BIP32.fromSeed(Buffer.alloc(32, seedByte), descriptors.networks.testnet)
    return {
      xpub: master.derivePath("m/48'/1'/0'/2'").neutered().toBase58(),
      fingerprint: Buffer.from(master.fingerprint).toString('hex'),
    }
  }
  const KEYS = [KEY1, KEY2, KEY3, keyAt(4), keyAt(5), keyAt(6), keyAt(7), keyAt(8)]
  /** The first `n` distinct keys — for asserting on SHAPE (m-of-n) rather than on bytes. */
  const nKeys = (n: number) => KEYS.slice(0, n)
  const build = (m: number, n: number) => () =>
    buildVaultDescriptor({ m, keys: nKeys(n), network: 'testnet' })

  it('is a STRICT majority — an even n needs MORE than half', () => {
    expect(minMajorityThreshold(1)).toBe(1)
    expect(minMajorityThreshold(2)).toBe(2)
    expect(minMajorityThreshold(3)).toBe(2)
    expect(minMajorityThreshold(5)).toBe(3)
    // 3-of-6 is refused: two disjoint groups of three could EACH spend without the other,
    // so the vault would have two independent owners while presenting itself as one.
    expect(minMajorityThreshold(6)).toBe(4)
    expect(minMajorityThreshold(15)).toBe(8)
  })

  it('never suggests a default the builder would then refuse', () => {
    for (let n = 2; n <= 15; n++) {
      expect(defaultThreshold(n)).toBeGreaterThanOrEqual(minMajorityThreshold(n))
    }
  })

  it('refuses a minority quorum even though every key is valid', () => {
    expect(build(1, 3)).toThrow(BuildDescriptorError)
    expect(build(2, 5)).toThrow(BuildDescriptorError)
    expect(build(3, 6)).toThrow(BuildDescriptorError)
    expect(build(3, 8)).toThrow(BuildDescriptorError)
  })

  it('explains itself in the error — it is the only place this rule is stated', () => {
    // The UI note was cut, so this message carries the whole explanation to the user.
    expect(build(2, 5)).toThrow(/majority/i)
    expect(build(2, 5)).toThrow(/at least 3 of 5/)
  })

  it('builds the smallest legal shape and everything above it', () => {
    expect(build(2, 3)).not.toThrow()
    expect(build(3, 3)).not.toThrow()
    expect(build(3, 5)).not.toThrow()
    expect(build(5, 8)).not.toThrow()
  })

  /*
    ⚠️ m === n stays a WARNING (isNoRedundancyQuorum), never a refusal — losing your only
    spare is a real trade someone can mean. This test is the one that fails if a later change
    "tidies" the two rules together.
  */
  it('refuses 1-of-2 but still BUILDS 2-of-2 — m === n is warned, not blocked', () => {
    expect(build(1, 2)).toThrow(BuildDescriptorError)
    expect(build(2, 2)).not.toThrow()
  })

  /*
    ⚠️ THE ORDERING TEST — the reason the refusal sits AFTER validateXpub rather than beside
    the m > n check. A key set with a broken key AND a sub-majority m must report the BROKEN
    KEY: a policy refusal that speaks first sends the user to fix the wrong thing. The SignBit
    platform's importer paid for this lesson three times; this is what stops a refactor from
    re-introducing it here.
  */
  it('reports a broken key BEFORE the policy refusal when a fixture has both', () => {
    expect(() =>
      buildVaultDescriptor({
        m: 1, // sub-majority: would be refused on its own
        keys: [KEY1, KEY2, { xpub: 'tprvfakeprivatekeyvalue', fingerprint: '00000000' }],
        network: 'testnet',
      }),
    ).toThrow(/PRIVATE key/)
  })
})
